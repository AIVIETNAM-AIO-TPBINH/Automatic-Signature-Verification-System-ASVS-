"""
Loss Functions for Signature Verification & Hard-Example Mining.
Implements:
1. Binary Cross Entropy with Logits (Standard baseline)
2. Binary Focal Loss (gamma=2.0)
   * ACADEMIC JUSTIFICATION ON BALANCED DATASETS (50% Genuine vs. 50% Forged):
     While Focal Loss was introduced by Lin et al. (RetinaNet, 2017) to combat extreme
     foreground-background class imbalance (1:1000), its foundational mathematical mechanism
     operates on SAMPLE DIFFICULTY DYNAMICS rather than label frequency alone.

     In Banking Signature Verification:
     a) Extreme Difficulty Disparity:
        - The negative class (forgeries) contains two distinct distributions:
          * Random / Coarse Forgeries: Radically different name/style. Easily classified with p_t ~ 0.99.
          * Skilled Forgeries: Professional impostors tracing stroke trajectory and curvature.
            These ambiguous samples reside in the critical boundary zone where p_t ~ 0.5 - 0.6.
     b) The Gradient Swamping Hazard:
        - Under standard BCE, even if an easy sample yields an individual loss of only ~0.01,
          the cumulative gradient across thousands of easy pairs dominates the mini-batch update,
          diluting the gradient signal generated by the few hard, skilled forgeries.
     c) Modulating Factor Dynamics:
        - Modulating factor (1 - p_t)^gamma with gamma=2.0:
          * For an easy sample (p_t = 0.99): (1 - 0.99)^2 = 0.0001 (gradient attenuated 10,000x).
          * For a hard skilled forgery (p_t = 0.50): (1 - 0.50)^2 = 0.2500 (gradient fully retained).
        - Consequently, Focal Loss acts as an automatic, continuous Online Hard Example Mining (OHEM)
          operator, focusing optimization on stroke-level skilled forgery discrimination.
3. Label Smoothing BCE (Mitigates overconfidence on stroke noise)
"""

from typing import Optional
import torch
import torch.nn as nn
import torch.nn.functional as F


class FocalLoss(nn.Module):
    """
    Binary Focal Loss:
        FL(p_t) = - alpha_t * (1 - p_t)^gamma * log(p_t)
    When gamma = 2.0, correctly classified easy examples (p_t ~ 0.99) receive near-zero loss,
    forcing the gradient update to concentrate on ambiguous and skilled forgeries.
    """
    def __init__(
        self,
        gamma: float = 2.0,
        alpha: Optional[float] = 0.25,
        reduction: str = "mean",
        eps: float = 1e-8
    ):
        super().__init__()
        self.gamma = gamma
        self.alpha = alpha
        self.reduction = reduction
        self.eps = eps

    def forward(self, logits: torch.Tensor, targets: torch.Tensor) -> torch.Tensor:
        # logits: (B,), targets: (B,) with values in {0, 1}
        probs = torch.sigmoid(logits)
        targets = targets.float()

        # p_t: probability of true class
        p_t = targets * probs + (1.0 - targets) * (1.0 - probs)
        p_t = torch.clamp(p_t, min=self.eps, max=1.0 - self.eps)

        # Modulating factor (1 - p_t)^gamma: drops loss to ~0 for well-classified examples
        modulating_factor = (1.0 - p_t) ** self.gamma

        # Binary cross entropy per element
        bce = -torch.log(p_t)

        loss = modulating_factor * bce

        if self.alpha is not None:
            alpha_t = targets * self.alpha + (1.0 - targets) * (1.0 - self.alpha)
            loss = alpha_t * loss

        if self.reduction == "mean":
            return loss.mean()
        elif self.reduction == "sum":
            return loss.sum()
        else:
            return loss


class LabelSmoothingBCE(nn.Module):
    """
    Binary Cross Entropy with Label Smoothing:
    Smooths target y -> y * (1 - eps) + 0.5 * eps.
    Prevents the model from driving logit magnitudes to extreme infinity.
    """
    def __init__(self, eps: float = 0.05, reduction: str = "mean"):
        super().__init__()
        self.eps = eps
        self.reduction = reduction

    def forward(self, logits: torch.Tensor, targets: torch.Tensor) -> torch.Tensor:
        smoothed_targets = targets * (1.0 - self.eps) + 0.5 * self.eps
        return F.binary_cross_entropy_with_logits(logits, smoothed_targets, reduction=self.reduction)


def get_loss_function(name: str = "focal", **kwargs) -> nn.Module:
    """
    Factory function returning the configured loss function.
    """
    name_lower = name.lower()
    if name_lower in ["focal", "focal_loss"]:
        gamma = kwargs.get("gamma", 2.0)
        alpha = kwargs.get("alpha", 0.25)
        return FocalLoss(gamma=gamma, alpha=alpha)
    elif name_lower in ["label_smoothing", "ls_bce"]:
        eps = kwargs.get("eps", 0.05)
        return LabelSmoothingBCE(eps=eps)
    elif name_lower in ["bce", "bce_with_logits"]:
        return nn.BCEWithLogitsLoss()
    else:
        raise ValueError(f"Unknown loss function name: {name}")
